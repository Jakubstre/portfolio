// Store the original HTML of each translatable element.
// This allows the page to return to its original English content.

const originalI18nContent = new WeakMap();

function setLanguage(language) {

  if (!translations[language]) return;


  // Translate regular text
  document.querySelectorAll("[data-i18n]").forEach(element => {

    const key = element.getAttribute("data-i18n");

    // Save original content once
    if (!originalI18nContent.has(element)) {
      originalI18nContent.set(element, element.innerHTML);
    }

    const translation = translations[language][key];

    if (translation !== undefined) {

      element.textContent = translation;

    } else {

      // Restore original content if no translation exists
      element.innerHTML = originalI18nContent.get(element);

    }

  });


  // Translate placeholders
  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {

    const key = element.getAttribute("data-i18n-placeholder");

    if (!originalI18nContent.has(element)) {
      originalI18nContent.set(element, element.getAttribute("placeholder") || "");
    }

    const translation = translations[language][key];

    if (translation !== undefined) {

      element.setAttribute("placeholder", translation);

    } else {

      element.setAttribute("placeholder", originalI18nContent.get(element));

    }

  });


  // Update active language button
  document.querySelectorAll(".language-option").forEach(button => {

    button.classList.toggle(
      "active",
      button.dataset.lang === language
    );

  });


  // Update document language
  document.documentElement.lang = language;


  // Save selected language
  localStorage.setItem("portfolioLanguage", language);

}


// ========================================
// LANGUAGE BUTTON EVENTS
// ========================================

document.querySelectorAll(".language-option").forEach(button => {

  button.addEventListener("click", () => {

    const language = button.dataset.lang;

    setLanguage(language);

    if (language === "sk" && typeof showTranslationNotice === "function") {
      showTranslationNotice();
    }

  });

});


// ========================================
// INITIALIZE SAVED LANGUAGE
// ========================================

document.addEventListener("DOMContentLoaded", () => {

  const savedLanguage = localStorage.getItem("portfolioLanguage") || "en";

  setLanguage(savedLanguage);

});